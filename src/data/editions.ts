export const languages = Array.from(
  new Set(editions.map((e) => e.language)),
).sort();

export const formats = Array.from(
  new Set(editions.map((e) => e.format)),
).sort();

export const editionsForWork = (work: WorkKey) =>
  editions.filter((e) => e.work === work);

export const editionCountForWork = (work: WorkKey) =>
  editionsForWork(work).length;

export const languageCountForWork = (work: WorkKey) =>
  new Set(editionsForWork(work).map((e) => e.language)).size;
